import type { GroupSummary } from '../stats/cuped.ts'
import demo from './demo-summaries.json'

export type BqMetric = 'conversion' | 'revenue'

export interface BqSummary {
  sample: boolean // true when the numbers come from the bundled sample data, not from BigQuery
  fallbackReason?: string // set when sample data is shown because BigQuery could not be reached
  project: string
  dataset: string
  table: string
  metric: BqMetric
  control: GroupSummary
  treatment: GroupSummary
}

interface RawGroup extends GroupSummary {
  variant: string
}

// Thrown when BigQuery cannot be used on this machine at all (API not running, no credentials, static host),
// as opposed to a problem with the request itself (unknown table, bad metric).
export class BqUnavailableError extends Error {}

// Ask the local API (server/index.ts) for per-variant aggregates of an experiment table.
export async function fetchSummary(table: string, metric: BqMetric): Promise<BqSummary> {
  let res: Response
  try {
    res = await fetch(`/api/bq/summary?table=${encodeURIComponent(table)}&metric=${metric}`)
  } catch {
    throw new BqUnavailableError('Cannot reach the BigQuery API. Start it in a second terminal with: yarn server')
  }
  const body = (await res.json().catch(() => null)) as { error?: string; project: string; dataset: string; table: string; metric: BqMetric; groups: RawGroup[] } | null
  if (!res.ok || !body) {
    // 401: no Google credentials; 404 / 5xx without a JSON error: no API behind /api (static host, server not running)
    if (res.status === 401) throw new BqUnavailableError(body?.error ?? 'Google credentials not found')
    if (!body?.error && (res.status === 404 || res.status >= 500)) throw new BqUnavailableError('The BigQuery API is not running. Start it in a second terminal with: yarn server')
    throw new Error(body?.error ?? `Request failed (${res.status})`)
  }
  const control = body.groups.find((g) => g.variant === 'control')
  const treatment = body.groups.find((g) => g.variant === 'treatment')
  if (!control || !treatment) throw new Error(`Table needs variants "control" and "treatment", found: ${body.groups.map((g) => g.variant).join(', ') || 'none'}`)
  return { sample: false, project: body.project, dataset: body.dataset, table: body.table, metric: body.metric, control, treatment }
}

type DemoTables = Record<string, Record<BqMetric, { control: GroupSummary; treatment: GroupSummary }>>

export const DEMO_TABLES = Object.keys(demo.tables)

// Bundled sample aggregates, generated by scripts/make-demo-data.ts with the recipe of docs/bigquery/setup.sql.
// Works without a Google account or the local API.
export function demoSummary(table: string, metric: BqMetric, fallbackReason?: string): BqSummary {
  const entry = (demo.tables as DemoTables)[table]?.[metric]
  if (!entry) throw new Error(`No sample data for table "${table}". Available: ${DEMO_TABLES.join(', ')}`)
  return { sample: true, fallbackReason, project: 'sample', dataset: 'ab_sandbox', table, metric, control: entry.control, treatment: entry.treatment }
}
