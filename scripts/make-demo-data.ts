// Generates src/bq/demo-summaries.json: per-variant aggregates for the four dummy tables, using the same
// recipe as docs/bigquery/setup.sql (propensity per user, lognormal order values, same 100k users in every
// table, only the treatment multiplier differs). Lets the BigQuery view work without a Google account.
//
//   yarn demo-data          # seed 1
//   yarn demo-data 7        # another seed
import { writeFileSync } from 'node:fs'
import { createRng, normalSample } from '../src/sim/rng.ts'

const N = 100_000
const SEED = Number(process.argv[2] ?? 1)
const MULTIPLIERS: Record<string, number> = { users: 1.15, users_loss: 0.85, users_aa: 1.0, users_small: 1.03 }

interface User {
  treat: boolean
  propensity: number
  uPre: number
  uPost: number
  nPre: number
  nPost: number
}

const rng = createRng(SEED)
const users: User[] = Array.from({ length: N }, () => ({
  treat: rng() < 0.5,
  // mean ~0.10; exp(0.8 z - 0.32) has mean 1
  propensity: Math.min(0.9, 0.1 * Math.exp(0.8 * normalSample(rng) - 0.32)),
  uPre: rng(),
  uPost: rng(),
  nPre: normalSample(rng),
  nPost: normalSample(rng),
}))

const order = (n: number) => Math.exp(Math.log(50) - 0.5 + n)

function group(ys: number[], xs: number[]) {
  const n = ys.length
  const my = ys.reduce((s, v) => s + v, 0) / n
  const mx = xs.reduce((s, v) => s + v, 0) / n
  let syy = 0
  let sxx = 0
  let sxy = 0
  for (let i = 0; i < n; i++) {
    syy += (ys[i] - my) ** 2
    sxx += (xs[i] - mx) ** 2
    sxy += (ys[i] - my) * (xs[i] - mx)
  }
  const r = (v: number) => Number(v.toPrecision(10))
  return { n, mean: r(my), variance: r(syy / (n - 1)), meanX: r(mx), varX: r(sxx / (n - 1)), cov: r(sxy / (n - 1)) }
}

const tables: Record<string, Record<string, Record<string, ReturnType<typeof group>>>> = {}
for (const [table, mult] of Object.entries(MULTIPLIERS)) {
  const cols = { conversion: { y: [[], []] as number[][], x: [[], []] as number[][] }, revenue: { y: [[], []] as number[][], x: [[], []] as number[][] } }
  for (const u of users) {
    const g = u.treat ? 1 : 0
    const preBought = u.uPre < u.propensity
    const bought = u.uPost < Math.min(1, u.propensity * (u.treat ? mult : 1))
    cols.conversion.y[g].push(bought ? 1 : 0)
    cols.conversion.x[g].push(preBought ? 1 : 0)
    cols.revenue.y[g].push(bought ? order(u.nPost) : 0)
    cols.revenue.x[g].push(preBought ? order(u.nPre) : 0)
  }
  tables[table] = {}
  for (const metric of ['conversion', 'revenue'] as const) {
    const c = cols[metric]
    tables[table][metric] = { control: group(c.y[0], c.x[0]), treatment: group(c.y[1], c.x[1]) }
  }
}

writeFileSync(
  new URL('../src/bq/demo-summaries.json', import.meta.url),
  JSON.stringify({ note: 'Generated by scripts/make-demo-data.ts with the recipe of docs/bigquery/setup.sql. Not read from BigQuery.', seed: SEED, users: N, tables }, null, 2) + '\n',
)
for (const [t, m] of Object.entries(tables)) {
  console.log(t.padEnd(12), 'conv control', m.conversion.control.mean.toFixed(4), 'treatment', m.conversion.treatment.mean.toFixed(4))
}
